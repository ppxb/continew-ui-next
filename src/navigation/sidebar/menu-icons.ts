const FALLBACK_ICON = AppWindow

function toPascalCase(str: string): string {
  return str
    .split('-')
    .map(part => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')
}

/**
 * Resolves an icon name from seeded aliases or any standard Lucide icon name.
 * Unknown names fall back to a generic page icon instead of leaving a gap.
 */
export function resolveMenuIcon(name?: string | null): LucideIcon {
  if (!name) {
    return FALLBACK_ICON
  }

  // Check custom admin aliases and overrides first
  if (MENU_ICONS[name]) {
    return MENU_ICONS[name]
  }

  // Fallback to any Lucide icon by name (kebab-case or PascalCase)
  const pascalName = toPascalCase(name)
  const dynamicIcon = (icons as Record<string, LucideIcon | undefined>)[pascalName]
  if (dynamicIcon) {
    return dynamicIcon
  }

  return FALLBACK_ICON
}
